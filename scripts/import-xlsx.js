#!/usr/bin/env node
/*
 * Import the 123 poles from the planning xlsx.
 *
 *   node scripts/import-xlsx.js path/to/Solar_Street_Lighting_Installation_Planning.xlsx
 *
 * Output:
 *   data/poles.json          — readable copy (used by tests)
 *   apps-script/SeedData.gs  — pasted into Apps Script; setup() writes it into the Google Sheet
 *
 * Sheet "Installation Plan", header row 5, data from row 6. The Zone column is ignored.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const XLSX = require('xlsx');
const L = require('../shared/logic.js');

const DEFAULT_SLOTS = [
  { SlotID: 'S1', Order: 1, Name: 'Peg / lokasi', Spec: '', Active: true },
  { SlotID: 'S2', Order: 2, Name: 'Menggali', Spec: '', Active: true },
  { SlotID: 'S3', Order: 3, Name: 'Ukuran', Spec: '1.5m × 1m', Active: true },
  { SlotID: 'S4', Order: 4, Name: 'Footing ditanam', Spec: '', Active: true },
  { SlotID: 'S5', Order: 5, Name: 'Leveling footing', Spec: '', Active: true },
  { SlotID: 'S6', Order: 6, Name: 'Lampu siap dipasang', Spec: '', Active: true },
  { SlotID: 'S7', Order: 7, Name: 'Ujian lampu', Spec: 'Waktu malam', Active: true }
];

function excelDateToIso(v) {
  if (v === null || v === undefined || v === '') return '';
  if (typeof v === 'number') {
    const d = new Date(Math.round((v - 25569) * 86400000));
    return d.toISOString().slice(0, 10);
  }
  const s = String(v).trim();
  let m = s.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (m) return `${m[1]}-${m[2]}-${m[3]}`;
  m = s.match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})$/); // DD/MM/YYYY
  if (m) return `${m[3]}-${m[2].padStart(2, '0')}-${m[1].padStart(2, '0')}`;
  throw new Error('Unrecognised date: ' + s);
}

function readPoles(xlsxPath) {
  const wb = XLSX.readFile(xlsxPath, { cellDates: false });
  const ws = wb.Sheets['Installation Plan'];
  if (!ws) throw new Error('Sheet "Installation Plan" not found');
  const rows = XLSX.utils.sheet_to_json(ws, { header: 1, raw: true, defval: null });
  const header = rows[4].map((h) => (h == null ? '' : String(h).trim())); // row 5
  const col = (name) => {
    const i = header.indexOf(name);
    if (i < 0) throw new Error('Column not found: ' + name);
    return i;
  };
  const cId = col('Light ID'), cBound = col('Bound'), cCh = col('Chainage / Location'),
    cWa = col('Work Area'), cDate = col('Planned Start Date');

  const poles = [];
  for (let r = 5; r < rows.length; r++) { // row 6 onwards
    const row = rows[r];
    if (!row || !row[cId]) continue;
    const id = String(row[cId]).trim();
    if (!/^SL-\d{3}$/.test(id)) throw new Error('Bad Light ID at row ' + (r + 1) + ': ' + id);
    const chainage = String(row[cCh] == null ? '' : row[cCh]).trim();
    const category = L.categoryFromWorkArea(row[cWa]);
    const installed = category === L.CATEGORY.INSTALLED;
    poles.push({
      PoleID: id,
      Bound: String(row[cBound]).trim().toUpperCase(),
      Chainage: chainage,
      ChainageExact: L.isChainageExact(chainage),
      Category: category,
      PlannedDate: excelDateToIso(row[cDate]),
      IsDone: installed,
      DoneBy: installed ? 'Import' : '',
      DoneAt: '',
      UpdatedAt: ''
    });
  }
  const ids = new Set(poles.map((p) => p.PoleID));
  if (ids.size !== poles.length) throw new Error('Duplicate Light IDs in xlsx');
  return poles;
}

function main() {
  const src = process.argv[2];
  if (!src) { console.error('Usage: node scripts/import-xlsx.js <file.xlsx>'); process.exit(1); }
  const poles = readPoles(src);
  const root = path.join(__dirname, '..');
  fs.writeFileSync(path.join(root, 'data/poles.json'), JSON.stringify(poles, null, 1) + '\n');
  const gs = '/* GENERATED by scripts/import-xlsx.js — do not edit by hand.\n' +
    ' * Used once by setup() to fill the Poles and Slots sheets. */\n' +
    'var SEED_POLES = ' + JSON.stringify(poles) + ';\n' +
    'var SEED_SLOTS = ' + JSON.stringify(DEFAULT_SLOTS) + ';\n';
  fs.writeFileSync(path.join(root, 'apps-script/SeedData.gs'), gs);
  const count = (f) => poles.filter(f).length;
  console.log(`Imported ${poles.length} poles: ` +
    `Sudah dipasang ${count((p) => p.Category === L.CATEGORY.INSTALLED)}, ` +
    `Perlu pasang ${count((p) => p.Category === L.CATEGORY.TODO)}, ` +
    `Tunggu kelulusan ${count((p) => p.Category === L.CATEGORY.PENDING)}; ` +
    `EB ${count((p) => p.Bound === 'EB')}, WB ${count((p) => p.Bound === 'WB')}; ` +
    `CH belum tepat ${count((p) => !p.ChainageExact)}`);
}

module.exports = { readPoles, DEFAULT_SLOTS, excelDateToIso };
if (require.main === module) main();
